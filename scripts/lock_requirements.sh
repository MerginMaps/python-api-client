#!/usr/bin/env bash
# Regenerate pinned dependency files from pyproject.toml:
#   requirements.txt       - runtime deps (bundled into the QGIS plugin as mergin/deps)
#   requirements.dev.txt   - runtime deps + direct dev/test deps (CI and local development)
#
# Run with the Python version the QGIS plugin and CI use (3.10):
#   PYTHON=python3.10 scripts/lock_requirements.sh
set -euo pipefail

PYTHON="${PYTHON:-python3.10}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

"$PYTHON" -c 'import sys; assert sys.version_info[:2] == (3, 10), f"expected Python 3.10, got {sys.version}"' \
    || { echo "Set PYTHON to a Python 3.10 interpreter" >&2; exit 1; }

freeze() {
    "$1/bin/pip" freeze --exclude-editable | grep -viE '^mergin[-_]client[= ]' | LC_ALL=C sort -f
}

# runtime dependencies only
"$PYTHON" -m venv "$TMP/prod"
"$TMP/prod/bin/pip" install -q --upgrade pip
"$TMP/prod/bin/pip" install -q "$ROOT"
{
    echo "# Pinned runtime dependencies (Python 3.10). Generated by scripts/lock_requirements.sh - do not edit."
    freeze "$TMP/prod"
} > "$ROOT/requirements.txt"

# runtime + dev/test dependencies
"$PYTHON" -m venv "$TMP/dev"
"$TMP/dev/bin/pip" install -q --upgrade pip
"$TMP/dev/bin/pip" install -q -r "$ROOT/requirements.txt"
"$TMP/dev/bin/pip" install -q --no-deps -e "$ROOT"
"$TMP/dev/bin/pip" install -q --group "$ROOT/pyproject.toml:dev"
{
    echo "# Pinned runtime + dev/test dependencies (Python 3.10). Generated by scripts/lock_requirements.sh - do not edit."
    echo "-r requirements.txt"
    # pin only the packages listed in the "dev" group; their own dependencies are resolved by pip at install time
    "$TMP/dev/bin/python" - "$ROOT/pyproject.toml" <<'EOF'
import re, sys
from importlib.metadata import version
try:
    import tomllib
except ImportError:  # Python 3.10
    import tomli as tomllib
with open(sys.argv[1], "rb") as f:
    group = tomllib.load(f)["dependency-groups"]["dev"]
names = sorted({re.split(r"[\s\[<>=!~;]", req, maxsplit=1)[0] for req in group}, key=str.lower)
for name in names:
    print(f"{name}=={version(name)}")
EOF
} > "$ROOT/requirements.dev.txt"

rm -rf "$ROOT/build" "$ROOT"/*.egg-info
echo "Updated requirements.txt and requirements.dev.txt"
